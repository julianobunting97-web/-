const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { chromium } = require(process.argv[2] || 'playwright')

async function main() {
  const output = path.resolve(__dirname, '../tmp/light-site-review')
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const errors = []
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.on('pageerror', error => errors.push(error.message))
  const shots = async name => page.screenshot({ path: path.join(output, `${name}.png`) })
  const noOverflow = async () => {
    const size = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }))
    assert.ok(size.scroll <= size.width + 1, `Horizontal overflow: ${JSON.stringify(size)}`)
  }
  try {
    await page.goto('http://localhost:4173/', { waitUntil: 'load' })
    await page.waitForTimeout(6000)
    await noOverflow()
    assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).colorScheme), 'light')
    await shots('desktop-hero')
    await page.locator('#about').scrollIntoViewIfNeeded()
    await page.waitForTimeout(1800)
    await shots('desktop-about')
    await page.locator('#projects').scrollIntoViewIfNeeded()
    await page.waitForTimeout(1800)
    const nav = await page.locator('.floating-nav').boundingBox()
    assert.ok(nav.y >= 0 && nav.y < 30)
    assert.ok(await page.locator('.nav-surface').evaluate(el => el.classList.contains('is-compact')))
    await shots('desktop-projects')
    await page.locator('.project-media-trigger').first().click()
    await page.waitForTimeout(600)
    const modal = await page.locator('.project-modal-shell').boundingBox()
    assert.ok(Math.abs(modal.x + modal.width / 2 - 720) < 2)
    await shots('desktop-gallery')
    await page.locator('.project-media-slot-copy button').first().click()
    await page.locator('.image-preview-canvas img').evaluate(img => img.decode())
    const scroll = await page.evaluate(() => window.scrollY)
    const canvas = page.locator('.image-preview-canvas')
    await canvas.hover()
    await page.mouse.wheel(0, -600)
    await page.waitForTimeout(350)
    assert.equal(await page.evaluate(() => window.scrollY), scroll)
    assert.notEqual(await page.locator('.image-preview-zoom').innerText(), '100%')
    await page.keyboard.press('ArrowRight')
    assert.match(await page.locator('.image-preview-count').innerText(), /^2\s*\//)
    await shots('desktop-original')
    await page.getByRole('button', { name: '关闭原图预览' }).click()
    await page.getByRole('button', { name: '关闭媒体弹层' }).click()
    const detail = await page.locator('.project-detail-link').first().getAttribute('href')
    await page.goto(new URL(detail, 'http://localhost:4173/').href, { waitUntil: 'load' })
    await page.waitForTimeout(1200)
    assert.equal(await page.locator('.project-detail-page').count(), 1)
    await noOverflow()
    await shots('desktop-detail')
    await page.goto('http://localhost:4173/#contact', { waitUntil: 'load' })
    await page.locator('#contact').scrollIntoViewIfNeeded()
    await page.waitForTimeout(5500)
    const contactBackground = await page.locator('.contact-card').evaluate(el => getComputedStyle(el).backgroundColor)
    assert.equal(contactBackground, 'rgb(251, 250, 246)')
    await shots('desktop-contact')
    assert.ok(await page.getByText('fengfan3812@gmail.com').count())

    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('http://localhost:4173/', { waitUntil: 'load' })
    await page.waitForTimeout(6000)
    await noOverflow()
    await shots('mobile-hero')
    await page.locator('#about').scrollIntoViewIfNeeded()
    await page.waitForTimeout(1200)
    await noOverflow()
    await shots('mobile-about')
    await page.locator('.project-media-trigger').first().click()
    await page.waitForTimeout(600)
    await noOverflow()
    await shots('mobile-gallery')
    await page.getByRole('button', { name: '关闭媒体弹层' }).click()
    await page.setViewportSize({ width: 1146, height: 986 })
    await page.goto('http://localhost:4173/', { waitUntil: 'load' })
    await page.waitForTimeout(5500)
    await noOverflow()
    await shots('tablet-hero')
    assert.deepEqual(errors, [])
    console.log('PASS: light theme, 3 viewports, fixed navigation, galleries, original zoom + scroll lock, image switching, project details, contact, and no JS errors.')
  } finally {
    await browser.close()
  }
}

main().catch(error => { console.error(error); process.exitCode = 1 })
